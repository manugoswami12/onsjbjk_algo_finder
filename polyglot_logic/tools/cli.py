#!/usr/bin/env python3
"""AP13 user input: one command-line interface for every AP13 activity.

  facts        SOURCE                    print language-neutral base facts
  scan         SOURCE [--store S]        branch + leaf recognition of any supported language
  learn        LABEL SOURCE FUNCTION     learn one reference (any language, normally Python)
  learn-corpus CORPUS AP11_STORE         learn every generated AP11 reference, read-only
  approve      LABEL approved|rejected|unreviewed
  status                                 catalog counts
  prefetch                               download the 7 tree-sitter grammars once (online)
  check        ...                       OPT-IN execution comparison, see io_check.py
Exit codes: 0 ok, 2 tool/input error (never reported as UNKNOWN).
"""
