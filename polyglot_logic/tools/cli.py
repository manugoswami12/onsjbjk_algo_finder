def facts_text(path: Path) -> tuple[str, str]:
    """Return (language, base facts text) for one source file."""
    try:
        return _facts_text(path)
    except ToolError:
        raise
    except (AttributeError, IndexError, KeyError, TypeError, ValueError, RecursionError) as exc:
        # a construct the lowering tables do not model: explicit error, never a guess
        raise ToolError(f'lowering failed ({type(exc).__name__}: {exc})') from exc


def _facts_text(path: Path) -> tuple[str, str]:
    lang, _, root = parse(path)
    if lang == 'prolog':
        lines = swipl('lower_main', [PROLOG_DIR / 'lower_prolog.pl'], [str(path.resolve())])
        seen, out = set(), ['% AP13 language-neutral base facts (generated by SWI read_term).']
        for line in lines:
            if line not in seen:
                seen.add(line)
                out.append(line)
        return lang, '\n'.join(out) + '\n'
    if lang == 'commonlisp':
        import lower_sexpr
        return lang, lower_sexpr.lower(root).text()
    if lang == 'haskell':
        import lower_equations
        return lang, lower_equations.lower(root).text()
    import lower_imperative
    return lang, lower_imperative.lower(lang, root).text()


def run_prolog(goal: str, facts: str, args: list[str]) -> list[str]:
    with tempfile.TemporaryDirectory(prefix='ap13_') as td:
        f = Path(td) / 'facts.pl'
        f.write_text(facts, encoding='utf-8')
        if goal in ('scan_main', 'gen_main'):
            # reference paths go through a list file: Windows caps a command line at ~32 KB
            lst = Path(td) / 'refs.txt'
            lst.write_text('\n'.join(args) + '\n', encoding='utf-8')
            args = ['@' + str(lst)]
        return swipl(goal, [AP12_ROUTER, PROLOG_DIR / 'main.pl'], [str(f), *args])


def scan(path: Path, store: Path, include_unreviewed: bool, quiet=False, qualities=('usable',)):
    lang, facts = facts_text(path)
    refs = store_mod.reference_files(store, include_unreviewed, qualities=qualities)
    have = store_mod.fact_features(facts)
    # sound prefilter: a reference needing an operator/call absent from the facts cannot match
    refs = [r for r in refs if store_mod.ref_features(r) <= have]
    result = report.parse_scan(run_prolog('scan_main', facts, [str(r) for r in refs]))
    result['library'] = report.library_calls(facts)
    if not quiet:
        report.show_scan(path, lang, result, len(refs))
    return result


def learn(label: str, path: Path, function: str, store: Path, origin='file', ap11_label='',
          category='') -> str:
    lang, facts = facts_text(path)
    lines = run_prolog('learn_main', facts, [function, label])
    head = lines[0].split('|') if lines else ['']
    if head[0] == 'LEARN_EMPTY':
        store_mod.record_attempt(store, label, 'no_effects', head[-1])
        return 'no_effects'
    if head[0] != 'LEARN' or len(head) != 5:
        raise ToolError('unexpected learn output: ' + ' / '.join(lines[:3]))
    clause = '\n'.join(lines[1:]) + '\n'
    row = dict(label=label, language=lang, source_path=str(path), function_name=function,
               branch=head[2], relations=int(head[3]), origin=origin, ap11_label=ap11_label,
               category=category, quality=head[4])
    return store_mod.save(store, row, clause) + f' branch={head[2]} relations={head[3]} quality={head[4]}'


def learn_file(path: Path, store: Path, prefix: str, relative: str, counts: dict):
    """G10: learn EVERY function of one source with one SWI-Prolog process."""
    lang, facts = facts_text(path)
    store_learned(store, lang, relative, run_prolog('learn_all_main', facts, [prefix]), counts)


def store_learned(store: Path, lang: str, relative: str, lines: list, counts: dict):
    """Save the LEARN blocks of one file (single writer: SQLite stays on one thread)."""
    i = 0
    while i < len(lines):
        head = lines[i].split('|')
        if head[0] == 'LEARN_EMPTY':
            store_mod.record_attempt(store, head[1], 'no_effects', head[2])
            counts['no_effects'] = counts.get('no_effects', 0) + 1
            i += 1
            continue
        if head[0] != 'LEARN' or len(head) != 6:
            raise ToolError('unexpected learn output: ' + lines[i][:200])
        j = lines.index('END', i)
        clause = '\n'.join(lines[i + 1:j]) + '\n'
        row = dict(label=head[1], language=lang, source_path=relative, function_name=head[5],
                   branch=head[2], relations=int(head[3]), origin='dir', ap11_label='',
                   category=relative.split('/')[0], quality=head[4])
        outcome = store_mod.save(store, row, clause)
        key = outcome if outcome == 'already_present' else head[4]  # usable / trivial
        counts[key] = counts.get(key, 0) + 1
        i = j + 1


STOP_TOKENS = {'recursive', 'iterative', 'simple', 'fast', 'naive', 'basic', 'optimized', 'with',
               'using', 'of', 'the', 'and', 'in', 'by', 'algorithm', 'algorithms', 'implementation',
               'sol1', 'sol2', 'sol3', 'sol4', 'main', 'test', 'tests', 'helper', 'py'}


def family_tokens(source_path: str) -> set:
    stem = source_path.rsplit('/', 1)[-1].rsplit('.', 1)[0]
    return {t for t in stem.lower().split('_') if t and t not in STOP_TOKENS and not t.isdigit()}


def generalize(corpus: Path, store: Path, workers: int = 4):
    """doc 07: for variants A (file X) and B (file Y) of one family, store the core of A
    that also holds in B, as a reference covering both."""
    from concurrent.futures import ThreadPoolExecutor
    meta = store_mod.metadata(store)
    usable = {l: m for l, m in meta.items() if m['quality'] == 'usable' and m['origin'] == 'dir'}
    by_file = {}
    for label, m in usable.items():
        by_file.setdefault(m['source_path'], []).append(label)
    files = sorted(by_file)
    toks = {f: family_tokens(f) for f in files}
    jobs = []
    for y in files:
        refs = [store / meta[l]['clause_path'] for x in files if x != y and len(toks[x] & toks[y]) >= 2
                for l in by_file[x]]
        if refs:
            jobs.append((y, refs))

    def run_job(job):
        y, refs = job
        try:
            _, facts = facts_text(corpus / y)
            return y, run_prolog('gen_main', facts, [str(r) for r in refs]), None
        except (ToolError, ValueError, OSError) as exc:
            return y, [], str(exc)
    counts = {'variant_pairs_files': len(jobs)}
    with ThreadPoolExecutor(max_workers=workers) as pool:
        for y, lines, err in pool.map(run_job, jobs):
            if err:
                counts['error'] = counts.get('error', 0) + 1
                print(f'AP13_GEN_ERROR: {y}: {err[:150]}')
                continue
            i = 0
            while i < len(lines):
                head = lines[i].split('|')
                if head[0] == 'SKIP':          # inference budget exceeded: no generalisation
                    counts['budget_skipped'] = counts.get('budget_skipped', 0) + 1
                    i += 1
                    continue
                if head[0] != 'GEN':
                    raise ToolError('unexpected generalize output: ' + lines[i][:200])
                j = lines.index('END', i)
                a = head[1]
                label = f"gen__{a}__{hashlib_short(y)}"
                clause = '\n'.join(lines[i + 1:j]).replace('reference(gen,', f'reference({label},', 1) + '\n'
                row = dict(label=label, language='python', source_path=meta[a]['source_path'],
                           function_name=meta[a]['function_name'], branch=head[2], relations=int(head[3]),
                           origin='generalized', ap11_label=a, category=meta[a]['category'],
                           quality='usable', also_source=y)
                outcome = store_mod.save(store, row, clause)
                counts[outcome] = counts.get(outcome, 0) + 1
                i = j + 1
    print('AP13_GENERALIZE: ' + ' '.join(f'{k}={v}' for k, v in sorted(counts.items())))
    return counts


def hashlib_short(text: str) -> str:
    import hashlib
    return hashlib.sha256(text.encode()).hexdigest()[:8]


def validate(corpus: Path, store: Path, workers: int = 4, min_files: int = 3, min_categories: int = 2):
    """doc 07 H1: a reference is NOT discriminative when it matches functions of >= min_files
    other corpus files (>= min_categories other categories) whose own references do not match
    it back. A mutual match is the same algorithm implemented twice (equivalence under the
    subsumption order) and never counts; a one-way match means the reference is a weaker
    sub-pattern of unrelated code. Such a reference becomes 'generic' and is never matched."""
    from concurrent.futures import ThreadPoolExecutor
    meta = store_mod.metadata(store)
    files = sorted({m['source_path'] for m in meta.values()} | {m['also_source'] for m in meta.values()
                                                                 if m['also_source']})
    files = [f for f in files if (corpus / f).is_file()]

    def run_one(f):
        try:   # generic references are scanned too, so re-validation sees them
            return f, scan(corpus / f, store, True, quiet=True, qualities=('usable', 'generic')), None
        except (ToolError, ValueError, OSError) as exc:
            return f, None, str(exc)
    hits = {}            # label -> {(file, function)}
    with ThreadPoolExecutor(max_workers=workers) as pool:
        for n, (f, r, err) in enumerate(pool.map(run_one, files), 1):
            if r:
                for x in r['leaves']:
                    if x['result'] in ('MATCH', 'CONTAINS'):    # any one-way hold counts
                        for fn in x['functions'].split(','):
                            hits.setdefault(x['label'], set()).add((f, fn))
            if n % 200 == 0:
                print(f'AP13_VALIDATE: {n}/{len(files)}', flush=True)
    labels_of = {}
    for label, m in meta.items():
        labels_of.setdefault((m['source_path'], m['function_name']), []).append(label)

    def matched_back(label, other):
        m = meta[label]
        return any((m['source_path'], m['function_name']) in hits.get(b, set()) for b in labels_of.get(other, []))
    updates, counts = {}, {}
    for label, m in meta.items():
        if m['quality'] not in ('usable', 'generic'):
            continue
        own = {m['source_path'], m['also_source']}
        one_way = sorted({f for f, fn in hits.get(label, set()) if f not in own and not matched_back(label, (f, fn))})
        own_cat = {p.split('/')[0] for p in own if p}
        cats = {p.split('/')[0] for p in one_way} - own_cat
        q = 'generic' if len(one_way) >= min_files and len(cats) >= min_categories else 'usable'
        updates[label] = (q, ';'.join(one_way[:20]))
        counts[q] = counts.get(q, 0) + 1
    store_mod.set_quality(store, updates)
    print('AP13_VALIDATE: ' + ' '.join(f'{k}={v}' for k, v in sorted(counts.items())))
    return counts


def learn_dir(root: Path, store: Path, limit: int, workers: int = 4):
    """Files are lowered and traced in parallel (independent subprocesses); results are
    stored in sorted file order by this thread only, so the catalog is deterministic."""
    import hashlib
    from concurrent.futures import ThreadPoolExecutor
    counts = {}
    files = sorted(p for p in root.rglob('*') if p.suffix.lower() in ('.py', '.rs', '.java', '.c', '.r',
                   '.hs', '.lisp', '.pl') and '.git' not in p.parts and p.is_file())[:limit]

    def trace(path):
        rel = path.relative_to(root).as_posix()
        prefix = 'lg_' + ''.join(ch if ch.isalnum() else '_' for ch in rel.rsplit('.', 1)[0])[:60] + \
            '_' + hashlib.sha256(rel.encode()).hexdigest()[:8]
        try:
            lang, facts = facts_text(path)
            return rel, prefix, lang, run_prolog('learn_all_main', facts, [prefix]), None
        except (ToolError, ValueError, OSError, RecursionError) as exc:
            return rel, prefix, None, None, exc

    with ThreadPoolExecutor(max_workers=workers) as pool:
        for n, (rel, prefix, lang, lines, exc) in enumerate(pool.map(trace, files), 1):
            if exc is None:
                try:
                    store_learned(store, lang, rel, lines, counts)
                except (ToolError, ValueError) as e:
                    exc = e
            if exc is not None:
                counts['error'] = counts.get('error', 0) + 1
                store_mod.record_attempt(store, prefix, 'error', f'{rel}: {exc}')
                print(f'AP13_LEARN_ERROR: {rel}: {str(exc)[:200]}', flush=True)
            if n % 100 == 0 or n == len(files):
                print(f'AP13_LEARN_DIR: {n}/{len(files)} ' + ' '.join(f'{k}={v}' for k, v in sorted(counts.items())),
                      flush=True)
    return counts


def learn_corpus(corpus: Path, ap11_store: Path, store: Path, categories, limit: int):
    import lower_imperative
    from lang_tables import SPEC  # noqa: F401  (python table must exist)
    counts = {}
    for row in store_mod.ap11_rows(ap11_store, tuple(categories), limit):
        try:
            path = store_mod.ap11_source_path(corpus, row['relative_path'])
            lang, _, root = parse(path)
            names = [n for _, n in lower_imperative.lower(lang, root).functions()
                     if n == row['function_name'] or n.split('.')[-1] == row['function_name']]
            if not names:
                raise ValueError('function not found by tree-sitter lowering')
            for name in names:  # qualified identity: Class.method never collides (P14)
                label = row['label'] if name == row['function_name'] else \
                    row['label'] + '__' + name.replace('.', '_')
                outcome = learn(label, path, name, store, 'ap11', row['label'], row['category'])
                key = outcome.split()[0]
                counts[key] = counts.get(key, 0) + 1
                print(f"AP13_LEARN: {label} {outcome}", flush=True)
        except (ToolError, ValueError, OSError) as exc:
            counts['error'] = counts.get('error', 0) + 1
            store_mod.record_attempt(store, row['label'], 'error', str(exc))
            print(f"AP13_LEARN_ERROR: {row['label']}: {exc}", flush=True)
    print('AP13_LEARN_CORPUS: ' + ' '.join(f'{k}={v}' for k, v in sorted(counts.items())))
    return counts


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--store', type=Path, default=store_mod.DEFAULT_STORE)
    sub = p.add_subparsers(dest='cmd', required=True)
    s = sub.add_parser('facts'); s.add_argument('source', type=Path)
    s = sub.add_parser('scan'); s.add_argument('source', type=Path)
    s.add_argument('--approved-only', action='store_true')
    s = sub.add_parser('learn'); s.add_argument('label'); s.add_argument('source', type=Path)
    s.add_argument('function')
    s = sub.add_parser('learn-corpus'); s.add_argument('corpus', type=Path); s.add_argument('ap11_store', type=Path)
    s.add_argument('--categories', nargs='*', default=['sorts', 'searches'])
    s.add_argument('--limit', type=int, default=5000)
    s = sub.add_parser('learn-dir', help='learn every function of every source under DIR')
    s.add_argument('directory', type=Path); s.add_argument('--limit', type=int, default=100000)
    s = sub.add_parser('generalize', help='merge variants of one algorithm family (doc 07)')
    s.add_argument('corpus', type=Path)
    s = sub.add_parser('validate', help='mark references that match unrelated corpus code (doc 07)')
    s.add_argument('corpus', type=Path)
    s = sub.add_parser('approve'); s.add_argument('label')
    s.add_argument('action', choices=['approved', 'rejected', 'unreviewed'])
    sub.add_parser('status')
    sub.add_parser('prefetch')
    s = sub.add_parser('check', help='OPT-IN: executes code in a temp dir with a timeout')
    s.add_argument('kind', choices=['sort', 'search'])
    s.add_argument('reference', type=Path); s.add_argument('ref_function')
    s.add_argument('candidate', type=Path); s.add_argument('cand_function')
    a = p.parse_args(argv)
    try:
        if a.cmd == 'facts':
            print(facts_text(a.source)[1], end='')
        elif a.cmd == 'scan':
            scan(a.source, a.store, not a.approved_only)
        elif a.cmd == 'learn':
            print('AP13_LEARN: ' + a.label + ' ' + learn(a.label, a.source, a.function, a.store))
        elif a.cmd == 'learn-corpus':
            counts = learn_corpus(a.corpus, a.ap11_store, a.store, a.categories, a.limit)
            return 2 if counts.get('error') else 0
        elif a.cmd == 'learn-dir':
            counts = learn_dir(a.directory, a.store, a.limit)
            return 2 if counts.get('error') else 0
        elif a.cmd == 'generalize':
            return 2 if generalize(a.corpus, a.store).get('error') else 0
        elif a.cmd == 'validate':
            validate(a.corpus, a.store)
        elif a.cmd == 'approve':
            store_mod.approve(a.store, a.label, a.action)
            print(f'AP13_REVIEW: {a.label} {a.action}')
        elif a.cmd == 'status':
            report.show_status(store_mod.status(a.store))
        elif a.cmd == 'prefetch':
            print('AP13_PREFETCH: ' + ','.join(prefetch()))
        elif a.cmd == 'check':
            import io_check
            return io_check.main(a)
    except (ToolError, ValueError, OSError) as exc:
        print(f'AP13_ERROR: {exc}', file=sys.stderr)
        return 2
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
