/* v0.2 learning (doc 04 section 14): a new algorithm learned from labelled Python files as a branch of the
   tree, at the node its logic reaches; the branch holds where a file at that node has the behaviour of
   the label's training files (input->output), and a second, more specific branch where it also has their write
   trace (the same writes to input positions in the same order: AP13 io_trace; doc 04 section 17). Deterministic:
   relations and behaviour, nothing counted.
     learn_main -- Reach Out : reads train(Label, File) (Label none: negative) and reach(File, Path) facts,
                               writes learned_branch(Node, Label, io, io) :- io_equal(Label). and
                               learned_branch(Node, Label, trace, io) :- io_trace_equal(Label). clauses
*/
:- dynamic train/2, reach/2.

% a file's node: its deepest path (the root [] when the tree has none for it)
node(F, C) :- findall(N-P, ( reach(F, P), length(P, N) ), Ps), msort(Ps, Sorted),
    ( last(Sorted, _-C) -> true ; C = [] ).

learn_main :-
    current_prolog_flag(argv, [Reach, Out|_]), load_files(Reach, [if(true)]),
    findall(C-L-F, ( train(L, F), L \== none, node(F, C) ), CLFs0), sort(CLFs0, CLFs),
    findall(C-L, member(C-L-_, CLFs), CLs0), sort(CLs0, CLs),
    setup_call_cleanup(open(Out, write, O), write_branches(O, CLs, CLFs), close(O)).

write_branches(O, CLs, CLFs) :-
    format(O, '/* GENERATED by prolog/learn_tree.pl (doc 04 section 14): one branch per label and tree node its~n   Python training files reach. Do not edit; relearn instead. */~n', []),
    format(O, ':- discontiguous learned_branch/4.~n:- dynamic io_equal/1, io_trace_equal/1.~n~n', []),
    forall(member(C-L, CLs),
           ( findall(F, member(C-L-F, CLFs), Fs), atomic_list_concat(C, '>', CA),
             format(O, '% ~w under [~w]: learned from ~w~n', [L, CA, Fs]),
             portray_clause(O, (learned_branch(C, L, io, io) :- io_equal(L))),
             portray_clause(O, (learned_branch(C, L, trace, io) :- io_trace_equal(L))) )).
