/* v0.2 learning (doc 04 sections 7-8): a new algorithm learned as a new branch of the tree, at the node
   its logic reaches, its condition a DCG found by running the fallback rule form backwards.
     learn_main -- Streams Out : reads train(Label, File, Tokens) (Label none: negative) and
                                 reach(File, Path) facts (the file's deepest family paths, tree_main.pl),
                                 writes learned_branch(Node, Label, Rule)//0 clauses to Out
   pattern(S)//1 is the form of every fallback rule (fallback_rules.pl): the tokens of S in order, with
   gaps. Like sum(2,X,10) and sum(X,5,20), the one relation runs both ways:
     apply:  S known, stream known      -> does the stream hold S          (phrase(pattern(S), Ts))
     learn:  streams of one label known -> S, the tokens they all hold     (pattern on every stream, S unbound)
   Names of functions of the file (link/enter/leave) are Prolog variables (AP13 G7: alpha-renaming),
   so unification across the streams relates the helpers of different files.
*/
:- dynamic train/3, reach/2.
:- prolog_load_context(directory, Dir), directory_file_path(Dir, 'flow_tokens.pl', T), load_files(T, []).

parses(S, Stream) :- copy_term(S, P), phrase(pattern(P), Stream, _), !.

% learn direction: S unbound, every stream known: the tokens of the first stream taken in order when
% every other stream holds them after its previous match (the streams in lockstep, nothing skipped
% first). The longest S found within a fixed inference budget is the most specific (AP13 generalize's
% budget, call_with_inference_limit/3).
shared(Streams, S) :-
    nb_setval(best, 0-[]),
    catch(call_with_inference_limit(( lockstep(Streams, S0), length(S0, N), nb_getval(best, B-_), N > B,
                                      nb_setval(best, N-S0), fail ; true ), 2000000, _), _, true),
    nb_getval(best, _-S), S \== [].
lockstep([First|Others], S) :- take(First, Others, S).
take(_, _, []).
take([T|Ts], Others, [T|S]) :- maplist(after(T), Others, Rest), take(Ts, Rest, S).
take([_|Ts], Others, S) :- take(Ts, Others, S).
after(T, Stream, Rest) :- phrase(next(T), Stream, Rest).

% ----- the node: where the logic of a file reaches the tree --------------------------------------
% a file reaches every prefix of its paths (the root [] always); its node is its deepest path
reaches(_, C) :- C == [], !.
reaches(F, C) :- reach(F, P), append(C, _, P), !.
node(F, C) :- findall(N-P, ( reach(F, P), length(P, N) ), Ps), msort(Ps, Sorted),
    ( last(Sorted, _-C) -> true ; C = [] ).

% ----- covering, one group of a label's files per node ----------------------------------------
learn_main :-
    current_prolog_flag(argv, [Streams, Out|_]), load_files(Streams, [if(true)]),
    findall(L, ( train(L, _, _), L \== none ), Ls0), sort(Ls0, Ls),
    setup_call_cleanup(open(Out, write, O), learn_all(Ls, O), close(O)).

learn_all(Ls, O) :-
    format(O, '/* GENERATED by prolog/learn_dcg.pl (doc 04 section 8): learned branches, each under the tree~n   node its training files reach, with the files it was learned from. Do not edit; relearn instead. */~n', []),
    format(O, ':- discontiguous learned_branch//3, learned_branch/4.~n:- dynamic io_equal/1.~n~n', []),
    forall(member(L, Ls), ( learn_label(L, Rules), write_rules(O, L, Rules) )).

learn_label(L, Rules) :-
    findall(C-F, ( train(L, F, _), node(F, C) ), CFs0), sort(CFs0, CFs),
    findall(C, member(C-_, CFs), Cs0), sort(Cs0, Cs),
    foldl(learn_node(L, CFs), Cs, 1-[], _-Rules0), append(Rules0, Rules).
% under node C: the negatives are the streams of the other training files that also reach C
learn_node(L, CFs, C, K0-Acc, K-[Rs|Acc]) :-
    findall(F, member(C-F, CFs), Fs),
    findall(T, ( train(L2, F2, T), L2 \== L, reaches(F2, C) ), Negs),
    cover(Fs, C, L, Negs, K0, K, Rs).
% one clause per file (Prolog's alternatives: p :- a. p :- b.), never a merge of files: a merge keeps only
% what the files share and can lose what separates the label at the node; a file that an earlier clause
% already covers gets none. Seed: the file's most specific stream.
cover(Fs, C, L, Negs, K0, K, Rules) :- cover(Fs, C, L, Negs, no_io, K0, K, Rules).
% a branch where a logic condition separates the file at C; only where none does, the input->output rule
% of the label at C (another predicate, learned_branch/4: it cannot change any branch's answers), once
cover([], _, _, _, _, K, K, []) :- !.
cover([F|Fs], C, L, Negs, Io, K0, K, Rules) :-
    K1 is K0 + 1, atom_concat(r, K0, R),
    (   seed(L, F, C, Negs, Seed), general(Seed, C, Negs, S)
    ->  exclude(covered_by(L, S), Fs, Rest),
        Rules = [branch(C, R, S, [F])|More], cover(Rest, C, L, Negs, Io, K1, K, More)
    ;   Io == no_io
    ->  Rules = [io(C, R, [F])|More], cover(Fs, C, L, Negs, io, K1, K, More)
    ;   Rules = [io_also(C, F)|More], cover(Fs, C, L, Negs, Io, K0, K, More)
    ).
seed(L, F, C, Negs, S) :-
    findall(N-T, ( train(L, F, T0), named_vars(T0, T), length(T, N) ), Ns), msort(Ns, Sorted),
    reverse(Sorted, Desc), member(_-S, Desc), enough(C, S), specific(S, Negs), !.
% the other end (version space): the most general rule below S, the same relation with the rule unbound
% over S itself: the shortest non-empty sub-pattern of S's logic tokens (operands are the language's
% spelling) that parses no negative under the node. At the root it keeps AP13's quality gate (4 logic
% tokens); under a node the node's own conditions are the logic, the rule only separates the label from
% the other programs there, so it needs some there to be separated from. None within the budget, or no
% other program at C: no branch works (fails).
general(_, _, [], _) :- !, fail.                  % nothing else at C: no evidence that a condition separates
general(S, C, Negs, G) :-
    include(logic_token, S, Ls), length(Ls, Max), ( C == [] -> Min = 4 ; Min = 1 ),
    catch(call_with_inference_limit(( between(Min, Max, N), length(G0, N), phrase(pattern(G0), Ls, _),
                                      specific(G0, Negs) -> true ), 5000000, R), _, fail),
    R \== inference_limit_exceeded, nonvar(G0), G = G0.
covered_by(L, S, F) :- train(L, F, T), parses(S, T), !.
specific(S, Negs) :- \+ ( member(N, Negs), parses(S, N) ).
enough([], S) :- !, informative(S).
enough(_, _).
% at least 4 tokens that say something about the logic (AP13's quality gate)
informative(S) :- include(logic_token, S, Ls), length(Ls, N), N >= 4.
logic_token(T) :- nonvar(T), \+ memberchk(T, [param, local, other, unknown, test, empty, elem, single]),
    \+ T = int(_), \+ T = enter(_), \+ T = leave(_), \+ T = link(_).

% the names of the file's own functions become variables, one per name (alpha-renaming)
named_vars(T0, T) :- named_vars(T0, T, [], _).
named_vars([], [], A, A).
named_vars([X0|Xs0], [X|Xs], A0, A) :- rename(X0, X, A0, A1), named_vars(Xs0, Xs, A1, A).
rename(X0, X, A0, A) :- compound(X0), X0 =.. [F, G], memberchk(F, [link, enter, leave]), atom(G), !,
    ( memberchk(G-V, A0) -> A = A0 ; A = [G-V|A0] ), X =.. [F, V].
rename(X, X, A, A).

% ----- the branches as DCG clauses (pattern//1: the same form as fallback_rules.pl) -----------------
write_rules(O, L, Rules) :-
    forall(member(Rule, Rules), write_rule(O, L, Rule)).
write_rule(O, L, branch(C, R, S, Used)) :-
    atomic_list_concat(C, '>', CA), format(O, '% ~w ~w under [~w], branch: learned from ~w~n', [L, R, CA, Used]),
    portray_clause(O, (learned_branch(C, L, R) --> pattern(S))).
write_rule(O, L, io(C, R, Used)) :-
    atomic_list_concat(C, '>', CA),
    format(O, '% ~w ~w under [~w], input->output (no logic condition separates it there): learned from ~w~n',
           [L, R, CA, Used]),
    portray_clause(O, (learned_branch(C, L, R, io) :- io_equal(L))).
write_rule(O, L, io_also(C, F)) :-
    atomic_list_concat(C, '>', CA), format(O, '% ~w under [~w]: ~w also only by input->output~n', [L, CA, F]).
