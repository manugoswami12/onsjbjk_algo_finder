"""Prompt library (doc 04 section 17.5): one prompt per rule written for TheAlgorithms/Python, with the rule it produced,
so that the same kind of rule can be written in future for a new file or a new corpus.

usage: python ta_prompts.py CORPUS      -> benchmark/rule_prompts.jsonl, docs/RULE_PROMPTS.md
Each entry: the label, its files, the kind of rule (file rule: prolog/ta_file_rules.pl; general relation:
prolog/ta_rules.pl), the prompt to run, and the clauses written. A file rule's prompt names the component chosen (from
ta_distinct.py); a general relation's prompt names the relation and its close negative (docs/HAND_RULES_WRITTEN.md).
"""
from __future__ import annotations

import json
import re
import sys
from collections import defaultdict
from pathlib import Path

import ta_corpus
from ta_corpus import ROOT

FILE_RULES = ROOT / 'prolog' / 'ta_file_rules.pl'
HAND_RULES = ROOT / 'prolog' / 'ta_rules.pl'
OUT = ROOT / 'benchmark' / 'rule_prompts.jsonl'
DOC = ROOT / 'docs' / 'RULE_PROMPTS.md'

FILE_PROMPT = (
    "Identify {files} as {label}. Run `python ta_distinct.py CORPUS --propose {label}` and keep the component that is "
    "the algorithm's own logic on its inputs: {component}. Write it as `hand_specific(_, '{label}') :- file_has(...)` "
    "in prolog/ta_file_rules.pl (or add {label} to benchmark/ta_file_rule_labels.json and run --write). Check with "
    "`eval_ta.py CORPUS --rehand --dir {folder}` and `--status`: every file of {label} answered {label} (T1), no other "
    "file answered {label} (T2).")
HAND_PROMPT = (
    "Write a general relation for {label} in prolog/ta_rules.pl, the same in every language: `hand_branch(Node, F, "
    "{label})` over the language-neutral facts (exchange/4, loops, under/2, loop_step/2, value/3, guards). Test it on "
    "an own Python program, an own program in another language and a close negative (tests/test_uniform.py "
    "HandRuleTests), then over the corpus (no new T2 claims) and the Rosetta files of its task (T3).")


def clauses(path: Path, head: str) -> dict[str, list[str]]:
    """{label: [clause text]} of the clauses whose head is `head`(_, label) or head(Node, F, label)."""
    out = defaultdict(list)
    text = path.read_text(encoding='utf-8')
    for m in re.finditer(rf"^{head}\(([^\n]*?)\) :-(.*?)\.\s*$", text, re.MULTILINE | re.DOTALL):
        label = m.group(1).split(',')[-1].strip().strip("'")
        if label[:1].isupper():                   # a rule naming several labels by a table (base_label/3)
            continue
        out[label].append(f"{head}({m.group(1)}) :-{m.group(2)}.")
    return out


def component_words(clause: str) -> str:
    """The component of a file rule as written (its file_has terms, \\+ marking an exclusion)."""
    parts = re.findall(r"(\\\+ )?file_has\((.*?)\)(?=, (?:\\\+ )?file_has|\.$)", clause.strip())
    return '; '.join(('not ' if neg else '') + term for neg, term in parts) or clause


def main():
    corpus = Path(sys.argv[1])
    labels = ta_corpus.files(corpus)
    files = defaultdict(list)
    for rel, lab in labels.items():
        files[lab].append(rel)
    entries = []
    for label, cs in sorted(clauses(FILE_RULES, 'hand_specific').items()):
        fs = files.get(label, [])
        comp = ' | '.join(component_words(c) for c in cs)
        entries.append({'label': label, 'files': fs, 'kind': 'file_rule', 'clauses': cs,
                        'prompt': FILE_PROMPT.format(label=label, files=', '.join(fs), component=comp,
                                                     folder=fs[0].split('/')[0] if fs else '-')})
    for label, cs in sorted(clauses(HAND_RULES, 'hand_branch').items()):
        entries.append({'label': label, 'files': files.get(label, []), 'kind': 'general_relation', 'clauses': cs,
                        'prompt': HAND_PROMPT.format(label=label)})
    OUT.write_text(''.join(json.dumps(e, sort_keys=True) + '\n' for e in entries), encoding='utf-8')
    by = defaultdict(list)
    for e in entries:
        by[e['kind']].append(e)
    doc = ['# Rule prompts: one per rule written (doc 04 section 17.5)', '',
           ('Run a prompt to write the same kind of rule for a new file. `benchmark/rule_prompts.jsonl` has every '
            'entry with its full prompt and the clauses it produced; generated by `python ta_prompts.py CORPUS`.'), '',
           f"- file rules (identify one corpus file): {len(by['file_rule'])} labels",
           f"- general relations (the same component in every language): {len(by['general_relation'])} labels", '',
           '## The two prompts', '', '> ' + FILE_PROMPT, '', '> ' + HAND_PROMPT, '',
           '## General relations', '', '| label | clauses |', '|---|---|']
    doc += [f"| {e['label']} | {len(e['clauses'])} |" for e in by['general_relation']]
    doc += ['', '## File rules (first 40 by label; all in the JSONL)', '', '| label | file(s) | component |', '|---|---|---|']
    doc += [f"| {e['label']} | {', '.join(e['files'])} | `{component_words(e['clauses'][0])[:110]}` |"
            for e in by['file_rule'][:40]]
    DOC.write_text('\n'.join(doc) + '\n', encoding='utf-8')
    print(f"{len(entries)} prompts -> {OUT}, {DOC}")


if __name__ == '__main__':
    main()
