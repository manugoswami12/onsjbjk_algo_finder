"""Separate test tool (doc 04 section 18.3): write the learned class branches into prolog/proposed_branches.pl.
Every TheAlgorithms/Python file decided new_version C (tools_manual/decide_new_or_known.py: its root functions ran on
every battery input and satisfy class relation C) gives the branch
    proposed_branch(Node, C) :- class_holds(C).
at every tree node the file reaches below a root (its logic structure, learn_facts.nodes). A root node (numeric,
sequence_query, sequence_transformation) holds 100s of files of 9+ tasks and gets no branch. Branches are learned
only from TheAlgorithms files; the held-out files are the test. The pipeline never loads this file.

usage: python tools_manual/write_branches.py CORPUS_DECIDED.json   -> prolog/proposed_branches.pl, benchmark/proposed_branches.json
"""
import json
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT, SOURCES = ROOT / 'prolog' / 'proposed_branches.pl', ROOT / 'benchmark' / 'proposed_branches.json'


def branches(decided: dict) -> dict[tuple[str, str], list[str]]:
    """{(node, class): [TheAlgorithms files it was learned from]}."""
    out = defaultdict(list)
    for rel, d in sorted(decided.items()):
        if d.get('decision') == 'new_version':
            for node in d.get('nodes', []):
                if '>' in node:                         # below a root
                    out[(node, d['class'])].append(rel)
    return out


def main():
    br = branches(json.loads(Path(sys.argv[1]).read_text(encoding='utf-8')))
    lines = ['/* v0.2 proposed class branches (doc 04 section 18.3), generated by tools_manual/write_branches.py: kept',
             '   separate from the pipeline. proposed_branch(Node, Class): at Node, a program whose root functions satisfy',
             "   Class's relation (prolog/class_specs.pl) on every battery input is a new version of Class.",
             '     proposed_main -- Facts : reads file_node/1 and holds/1, prints PROPOSED|Node|Class',
             '   A branch at Node also covers the nodes below it (a variation in its family), never the nodes above.',
             '*/',
             ':- dynamic file_node/1, holds/1.', '',
             'proposed_main :- current_prolog_flag(argv, [Facts|_]), load_files(Facts, [if(true)]),',
             "    forall(distinct(M-C, applies(M, C)), format('PROPOSED|~w|~w~n', [M, C])).",
             'applies(M, C) :- proposed_branch(M, C), file_node(N), under_or_at(N, M).',
             "under_or_at(N, M) :- N == M, !.",
             "under_or_at(N, M) :- atom_concat(M, '>', P), sub_atom(N, 0, _, _, P).",
             'class_holds(C) :- holds(C).', '']
    for (node, cls), rels in sorted(br.items()):
        lines.append(f"proposed_branch({node!r}, {cls}) :- class_holds({cls}).   % from {', '.join(rels)}".replace('"', "'"))
    OUT.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    SOURCES.write_text(json.dumps({f'{n}|{c}': rels for (n, c), rels in sorted(br.items())}, indent=1) + '\n',
                       encoding='utf-8')
    print(f'{len(br)} branches -> {OUT}')


if __name__ == '__main__':
    main()
