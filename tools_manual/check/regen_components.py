"""Regenerate only prolog/ta_file_components.pl (the fingerprint facts same_file/1 checks) from benchmark/ta_signatures.json,
exactly as ta_distinct.write_rules writes it; prolog/ta_file_rules.pl is not touched."""
import json, sys
from pathlib import Path
sys.path[:0] = ['.']
import ta_corpus, ta_distinct
labels = ta_corpus.files(Path(sys.argv[1]))
todo = set(json.loads(ta_distinct.RULE_LABELS.read_text(encoding='utf-8')))
sigs = json.loads(ta_distinct.INDEX.read_text(encoding='utf-8'))
facts = ['% GENERATED by ta_distinct.py --write: the components of each file of a label with a file rule (same_file/1)',
         ':- discontiguous label_file_component/3.']
for rel, lab in sorted(labels.items()):
    if lab in todo:
        facts += [f"label_file_component('{lab}', '{rel}', {c})." for c in sigs.get(rel, [])]
ta_distinct.COMPONENTS.write_text('\n'.join(facts) + '\n', encoding='utf-8')
print(len(facts), 'facts ->', ta_distinct.COMPONENTS)
